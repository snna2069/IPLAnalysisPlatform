select
    delivery_id,
    match_id,
    innings_number,
    over_number,
    ball_number,
    batting_team,
    is_super_over,
    batter,
    bowler,
    non_striker,
    batter_runs,
    extra_runs,
    total_runs,
    wides,
    no_balls,
    byes,
    leg_byes,
    penalty_runs,
    player_out,
    dismissal_kind,
    iff(batter_runs = 4 and not is_non_boundary, 1, 0) as is_four,
    iff(batter_runs = 6 and not is_non_boundary, 1, 0) as is_six,
    team_wickets as is_wicket,
    bowler_wickets,
    total_runs - byes - leg_byes - penalty_runs as bowler_runs_conceded,
    iff(wides = 0, 1, 0) as is_ball_faced,
    iff(wides > 0 or no_balls > 0, 1, 0) as is_illegal_delivery,
    source_file,
    file_hash,
    loaded_at
from {{ ref('stg_deliveries') }}
